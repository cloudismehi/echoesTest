#include <iostream> 
#include <vector> 

#include <raylib.h>
#include <raymath.h> 
#include <new>

#include "include/ProjectInfo.hpp"

// single delay instance, with a set time of delay time in samples
class DelayUnit{
    private: 
    // length of delay in samples
    long delayLength; 
    // storage bucket for delay memory
    double *cache; 
    // pointer for reading/writing values in cache
    long ptr = 0; 

    public: 
    /*
    DelayUnit(delayTime): sets the delay time n (default 10 samples) and creates the cache 
    array of size n which is the maximum size we need for the delay
    */
    DelayUnit(int length = 10); 

    // changeDelayTime(newDelayTime): sets delay time in samples
    void changeDelayTime(double newLength); 

    /*
    feed(newInput): main class function. stores new value in the cache at the current read index plus one 
    and returns the current index value from the cache, which is the value stored n samples ago. If nothing had been stored yet, it returns 
    zero
    parameters: new value [double]
    return: old cached value or zero
    */
   double feed(double input); 

   // helper function that prints delay length in samples for the unit 
   void printDelayLegnth(); 
}; 

class DelayLine{
    public: 
    /*
    a vector with all the delay lines, this vector is  filled in the class constructor with the information stored
    in the delaySettings Vector2
    */ 
    std::vector<DelayUnit> delayLine; 
    // the number of needed delays, set by the project settings and utilized first by the raytracing algorithm
    int numberOfDelayUnits = 1; 
    /*
    holds the delay information generated by the raytracing [delayTime, distanceTraveled]
    this vector must be filled by the class constructor with the necessary information. 
    */ 
    std::vector<Vector2> delaySettings;
    // project info from the project info header file
    ProjectInfo projectInfo; 

    /*
    DelayLine(# of delays, delay settings vector): initializes the delay line with the prescribed number of delay units
    at the prescribed delay times; both values to be passed: one by user choice and the other from the raytracing algorithm
    parameters: number of delays [int], delay information [vector2{delay time(s), delay distance(m)}]
    */
    DelayLine(int _numberOfDelayUnits, std::vector<Vector2> _delaySettings); 

    // helper function that prints all delayTimes in s for debugging
    void printDelayTimes(); 

    /*
    helper function that turns seconds into samples using the project info's delay time which is what the delay unit needs in its constructor 
    parameter: time in seconds
    output: time in samples 
    */ 
    float secondsToSamples(float seconds); 

    // feed all delay units and get back sum of all delayed values 
    double feed(double input); 
}; 

